PROJECT_ROOT = Path(__file__).resolve().parent.parent
ORIGINAL_FIRMWARE = PROJECT_ROOT / "src" / "xiao_nrf52840_sense" / "circuitpython" / "code.py"


def generate_neopixel_firmware(pin_name: str, num_pixels: int, brightness: float) -> str:
    """Generate self-contained CircuitPython code using built-in neopixel_write."""
    return f'''"""CJMCU-2812-8 / WS2812 8-LED Stick Hardware Verification Firmware.
Generated by tools/test_neopixel.py.
Configured Pin: board.{pin_name} | Pixels: {num_pixels} | Brightness: {int(brightness * 100)}%
"""

import time
import board
import digitalio
import neopixel_write

NUM_PIXELS = {num_pixels}
BRIGHTNESS = {brightness:.3f}
PIN_NAME = "{pin_name}"

# Initialize GPIO pin for WS2812 bitbang
pin_obj = getattr(board, PIN_NAME, None)
if pin_obj is None:
    raise ValueError(f"Pin {{PIN_NAME}} not found on board")

led_pin = digitalio.DigitalInOut(pin_obj)
led_pin.direction = digitalio.Direction.OUTPUT

print("\\n" + "=" * 55)
print(f"  CJMCU-2812-8 HARDWARE TEST -- PIN {{PIN_NAME}} ({{NUM_PIXELS}} LEDs)")
print(f"  Brightness: {{int(BRIGHTNESS * 100)}}% | Built-in neopixel_write")
print("=" * 55 + "\\n")


def write_pixels(colors):
    """Write RGB color tuples [(r, g, b), ...] in GRB WS2812 format."""
    buf = bytearray(NUM_PIXELS * 3)
    for i in range(min(len(colors), NUM_PIXELS)):
        r, g, b = colors[i]
        idx = i * 3
        # WS2812 expects GRB order:
        buf[idx] = int(g * BRIGHTNESS)
        buf[idx + 1] = int(r * BRIGHTNESS)
        buf[idx + 2] = int(b * BRIGHTNESS)
    neopixel_write.neopixel_write(led_pin, buf)


def clear():
    write_pixels([(0, 0, 0)] * NUM_PIXELS)


def wheel(pos):
    """Generate rainbow colors across 0-255 positions."""
    pos = pos % 256
    if pos < 85:
        return (255 - pos * 3, pos * 3, 0)
    elif pos < 170:
        pos -= 85
        return (0, 255 - pos * 3, pos * 3)
    else:
        pos -= 170
        return (pos * 3, 0, 255 - pos * 3)


# Main test loop
iteration = 0
colors_demo = [
    (255, 0, 0),      # Red
    (255, 128, 0),    # Amber
    (255, 255, 0),    # Yellow
    (0, 255, 0),      # Green
    (0, 255, 255),    # Cyan
    (0, 0, 255),      # Blue
    (180, 0, 255),    # Purple
    (255, 255, 255),  # White
]

while True:
    iteration += 1
    print(f"[TEST ITERATION {{iteration}}] Starting test sequence...")

    # Pattern 1: Single Pixel Addressing March (verifies each pixel individually)
    print("  [1/4] Single Pixel Walk (0 -> 7)...")
    for i in range(NUM_PIXELS):
        frame = [(0, 0, 0)] * NUM_PIXELS
        frame[i] = colors_demo[i % len(colors_demo)]
        write_pixels(frame)
        time.sleep(0.12)
    clear()
    time.sleep(0.15)

    # Pattern 2: Solid Primary Color Flashes
    print("  [2/4] Solid Primary Checks (Red -> Green -> Blue -> White)...")
    for name, c in [("RED", (255, 0, 0)), ("GREEN", (0, 255, 0)), ("BLUE", (0, 0, 255)), ("WHITE", (255, 255, 255))]:
        write_pixels([c] * NUM_PIXELS)
        time.sleep(0.35)
        clear()
        time.sleep(0.10)

    # Pattern 3: Bouncing Pendulum Sweep (Knight Rider scan)
    print("  [3/4] Bouncing Pendulum Sweep...")
    # Forward and backward 2 passes
    for _ in range(2):
        # Sweep right: 0 -> NUM_PIXELS - 1
        for pos in range(NUM_PIXELS):
            frame = [(0, 0, 0)] * NUM_PIXELS
            frame[pos] = (0, 180, 255)  # Head (cyan/blue)
            if pos > 0:
                frame[pos - 1] = (0, 30, 80)  # Trail
            write_pixels(frame)
            time.sleep(0.06)

        # Sweep left: NUM_PIXELS - 1 -> 0
        for pos in range(NUM_PIXELS - 1, -1, -1):
            frame = [(0, 0, 0)] * NUM_PIXELS
            frame[pos] = (0, 180, 255)  # Head
            if pos < NUM_PIXELS - 1:
                frame[pos + 1] = (0, 30, 80)  # Trail
            write_pixels(frame)
            time.sleep(0.06)
    clear()
    time.sleep(0.15)

    # Pattern 4: Smooth Rainbow Flow
    print("  [4/4] Rainbow Cycle...")
    for j in range(256):
        frame = [wheel((int(i * 256 / NUM_PIXELS) + j) & 255) for i in range(NUM_PIXELS)]
        write_pixels(frame)
        time.sleep(0.01)
    clear()
    time.sleep(0.30)
'''


def cmd_restore(drive_path: Path, port: str | None) -> int:
    """Restore the original project code.py from backup or repository source."""
    dest_code = drive_path / "code.py"
    backup_file = drive_path / "code_backup.py"

    if backup_file.exists():
        print(f"[RESTORE] Found backup at {backup_file}. Restoring...")
        shutil.copy2(backup_file, dest_code)
    elif ORIGINAL_FIRMWARE.exists():
        print(f"[RESTORE] Restoring from repository firmware: {ORIGINAL_FIRMWARE}")
        shutil.copy2(ORIGINAL_FIRMWARE, dest_code)
    else:
        print("[ERROR] Neither code_backup.py nor repository code.py found!")
        return 1

    print("[RESTORE] Successfully restored original code.py.")
    if port:
        print(f"[RESTORE] Sending soft-reset to {port}...")
        try:
            with serial.Serial(port, baudrate=115200, timeout=0.1) as ser:
                trigger_soft_reboot(ser)
            print("[RESTORE] Board rebooted into original firmware.")
        except Exception as e:
            print(f"[WARN] Could not soft-reboot over serial: {e}")
    return 0


def stream_monitor(port: str, duration: float = 0.0) -> None:
    """Stream live serial monitor output from the XIAO."""
    print(f"\n[MONITOR] Listening on {port} (115200 baud). Press Ctrl-C to stop monitor.\n")
    start = time.monotonic()
    try:
        with serial.Serial(port, baudrate=115200, timeout=0.1) as ser:
            while True:
                if duration > 0 and (time.monotonic() - start) >= duration:
                    break
                line = ser.readline()
                if line:
                    sys.stdout.write(line.decode("utf-8", errors="replace"))
                    sys.stdout.flush()
    except KeyboardInterrupt:
        print("\n[MONITOR] Exiting monitor.")
    except Exception as err:
        print(f"\n[MONITOR ERROR] Serial communication failed: {err}")


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Deploy and run NeoPixel stick (CJMCU-2812-8) hardware test on XIAO nRF52840",
    )
    parser.add_argument(
        "--pin",
        "-p",
        default="D0",
        help="XIAO GPIO pin connected to DIN (e.g. D0, D1, D2, D3, D6). Default: D0",
    )
    parser.add_argument(
        "--count",
        "-n",
        type=int,
        default=8,
        help="Number of pixels on the NeoPixel strip/stick. Default: 8",
    )
    parser.add_argument(
        "--brightness",
        "-b",
        type=float,
        default=0.20,
        help="Brightness float from 0.05 (5%%) to 1.0 (100%%). Default: 0.20 (safe for eyes & USB)",
    )
    parser.add_argument(
        "--drive",
        help="Explicit drive path for CIRCUITPY (e.g. 'F:\\').",
    )
    parser.add_argument(
        "--port",
        help="Explicit COM port for XIAO (e.g. 'COM5').",
    )
    parser.add_argument(
        "--no-monitor",
        action="store_true",
        help="Deploy test firmware without opening live serial monitor.",
    )
    parser.add_argument(
        "--duration",
        "-d",
        type=float,
        default=0.0,
        help="Duration to monitor serial in seconds (0 = indefinite until Ctrl-C).",
    )
    parser.add_argument(
        "--restore",
        "-r",
        action="store_true",
        help="Restore original project code.py from backup and exit.",
    )

    args = parser.parse_args()

    # Discover device
    info = discover_device(args.drive, args.port)
    if not info.drive_path:
        print("[ERROR] Could not find mounted CIRCUITPY drive.")
        return 1

    drive_path = info.drive_path
    com_port = info.com_port

    print("=" * 60)
    print("  XIAO nRF52840 -- CJMCU-2812-8 NEOPIXEL TEST LAUNCHER")
    print("=" * 60)
    print(f"  Drive       : {drive_path} (Label: {info.volume_label})")
    print(f"  Serial Port : {com_port or 'Not detected'}")

    if args.restore:
        return cmd_restore(drive_path, com_port)

    # Validate pin format
    pin_name = args.pin.upper().strip()
    if not pin_name.startswith("D") and pin_name.isdigit():
        pin_name = f"D{pin_name}"

    print(f"  Target Pin  : board.{pin_name}")
    print(f"  Pixel Count : {args.count}")
    print(f"  Brightness  : {int(args.brightness * 100)}%")
    print("=" * 60)

    # 1. Backup existing code.py if not already backed up
    current_code = drive_path / "code.py"
    backup_code = drive_path / "code_backup.py"
    if current_code.exists():
        code_text = current_code.read_text(encoding="utf-8", errors="replace")
        if "tools/test_neopixel.py" not in code_text:
            print(f"[BACKUP] Backing up current code.py -> {backup_code}...")
            shutil.copy2(current_code, backup_code)

    # 2. Generate and write test code.py
    test_code = generate_neopixel_firmware(pin_name, args.count, args.brightness)
    print(f"[DEPLOY] Writing NeoPixel test firmware to {current_code}...")
    current_code.write_text(test_code, encoding="utf-8")
    time.sleep(0.3)

    # 3. Soft-reset board over serial so CircuitPython runs the new script immediately
    if com_port:
        print(f"[RESET] Triggering soft-reboot on {com_port}...")
        try:
            with serial.Serial(com_port, baudrate=115200, timeout=0.1) as ser:
                trigger_soft_reboot(ser)
            print("[RESET] Board rebooted successfully!")
        except Exception as err:
            print(f"[WARN] Soft reboot warning: {err} (CircuitPython auto-reloads on file save anyway)")

    # 4. Stream monitor if requested
    if not args.no_monitor and com_port:
        time.sleep(0.5)
        stream_monitor(com_port, duration=args.duration)

    return 0


if __name__ == "__main__":
    sys.exit(main())
